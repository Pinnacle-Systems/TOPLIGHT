import { MD3DarkTheme, MD3LightTheme } from 'react-native-paper';
import { DarkTheme as NavigationDarkTheme, DefaultTheme as NavigationLightTheme } from '@react-navigation/native';
import { colorPalettes } from './palettes';
import {
    controlSizes,
    durations,
    elevation,
    fontFamilies,
    fontSizes,
    fontWeights,
    layout,
    letterSpacing,
    lineHeights,
    radii,
    spacing,
    typography,
    zIndex,
} from './tokens';

export function createAppTheme(mode = 'light') {
    const isDark = mode === 'dark';
    const colors = colorPalettes[isDark ? 'dark' : 'light'];
    const paperBase = isDark ? MD3DarkTheme : MD3LightTheme;
    const navigationBase = isDark ? NavigationDarkTheme : NavigationLightTheme;
    const paper = {
        ...paperBase,
        dark: isDark,
        roundness: radii.md,
        colors: {
            ...paperBase.colors,
            primary: colors.brand,
            primaryContainer: colors.brandSoft,
            secondary: colors.secondary,
            secondaryContainer: colors.secondarySoft,
            tertiary: colors.accent,
            tertiaryContainer: colors.accentSoft,
            background: colors.background,
            surface: colors.surface,
            surfaceVariant: colors.surfaceSunken,
            error: colors.danger,
            onPrimary: colors.brandContrast,
            onSecondary: colors.brandContrast,
            onBackground: colors.text,
            onSurface: colors.text,
            onSurfaceVariant: colors.textSecondary,
            outline: colors.border,
            outlineVariant: colors.borderSubtle,
            inverseSurface: colors.text,
            inverseOnSurface: colors.surface,
            inversePrimary: colors.brandStrong,
            scrim: colors.scrim,
            shadow: colors.shadow,
        },
    };

    const navigation = {
        ...navigationBase,
        dark: isDark,
        colors: {
            ...navigationBase.colors,
            primary: colors.brand,
            background: colors.background,
            card: colors.surface,
            text: colors.text,
            border: colors.borderSubtle,
            notification: colors.danger,
        },
    };

    const styles = {
        screen: { flex: 1, backgroundColor: colors.background },
        scrollContent: { flexGrow: 1, padding: layout.screenGutter, backgroundColor: colors.background },
        surface: { backgroundColor: colors.surface },
        card: {
            backgroundColor: colors.surface,
            borderColor: colors.borderSubtle,
            borderWidth: 1,
            borderRadius: radii.lg,
            padding: spacing.lg,
        },
        divider: { height: layout.dividerWidth, backgroundColor: colors.divider },
        heading: { ...typography.h2, color: colors.text },
        title: { ...typography.title, color: colors.text },
        body: { ...typography.body, color: colors.text },
        secondaryText: { ...typography.bodySmall, color: colors.textSecondary },
        caption: { ...typography.caption, color: colors.textMuted },
        input: {
            height: controlSizes.inputHeight,
            paddingHorizontal: spacing.md,
            borderWidth: 1,
            borderColor: colors.inputBorder,
            borderRadius: radii.md,
            color: colors.text,
            backgroundColor: colors.inputBackground,
            ...typography.body,
        },
        button: {
            minHeight: controlSizes.buttonHeight,
            alignItems: 'center',
            justifyContent: 'center',
            paddingHorizontal: spacing.lg,
            borderRadius: radii.md,
            backgroundColor: colors.brand,
        },
        buttonLabel: { ...typography.button, color: colors.brandContrast },
        buttonSecondary: {
            minHeight: controlSizes.buttonHeight,
            alignItems: 'center',
            justifyContent: 'center',
            paddingHorizontal: spacing.lg,
            borderWidth: 1,
            borderColor: colors.border,
            borderRadius: radii.md,
            backgroundColor: colors.surface,
        },
        buttonSecondaryLabel: { ...typography.button, color: colors.text },
        disabled: { backgroundColor: colors.disabledBackground, opacity: 0.7 },
        errorText: { ...typography.bodySmall, color: colors.danger },
        successText: { ...typography.bodySmall, color: colors.success },
        mutedText: { ...typography.bodySmall, color: colors.textMuted },
        listItem: {
            minHeight: controlSizes.minTouchTarget,
            flexDirection: 'row',
            alignItems: 'center',
            paddingVertical: spacing.sm,
            paddingHorizontal: spacing.md,
            backgroundColor: colors.surface,
            borderBottomWidth: layout.dividerWidth,
            borderBottomColor: colors.divider,
        },
        badge: {
            alignSelf: 'flex-start',
            paddingHorizontal: spacing.sm,
            paddingVertical: spacing.xs,
            borderRadius: radii.pill,
        },
        badgeSuccess: { backgroundColor: colors.successSoft },
        badgeWarning: { backgroundColor: colors.warningSoft },
        badgeDanger: { backgroundColor: colors.dangerSoft },
        badgeInfo: { backgroundColor: colors.infoSoft },
        modalBackdrop: {
            flex: 1,
            justifyContent: 'center',
            padding: layout.screenGutter,
            backgroundColor: colors.scrim,
        },
        modalSurface: {
            padding: spacing.xl,
            borderRadius: radii.xl,
            backgroundColor: colors.surfaceRaised,
        },
        emptyState: {
            flexGrow: 1,
            alignItems: 'center',
            justifyContent: 'center',
            padding: spacing.xxl,
            backgroundColor: colors.background,
        },
        shadow: {
            shadowColor: colors.shadow,
            shadowOffset: { width: 0, height: 2 },
            shadowOpacity: isDark ? 0.28 : 0.08,
            shadowRadius: 8,
            elevation: elevation.sm,
        },
    };

    return {
        mode: isDark ? 'dark' : 'light',
        isDark,
        colors,
        paper,
        navigation,
        spacing,
        radii,
        fontFamilies,
        fontSizes,
        fontWeights,
        lineHeights,
        letterSpacing,
        typography,
        controlSizes,
        layout,
        zIndex,
        elevation,
        durations,
        styles,
    };
}
